#!/usr/bin/env python3
"""Build/test the pinned public source in a new directory; never run its main."""
import argparse
import errno
import hashlib
import json
import platform
import re
import shutil
import subprocess
from pathlib import Path
import patch

BASE_COMMIT = '309d3a9809179d5d331d5adbd7dea7275200ed80'
CANDIDATE_SOURCE_SHA256 = 'd354ab6a4ef5dd9a5685a80682ee05cfdb989274b2c0a6f07b877d311939597b'
FILES = ('build.py','patch.py','bridge_stream_io.h','test_build.py',
         'test_transport.c','test_integration.c','helper-only.c',
         'continuous-cycle.py','timer-after-stall.c')
def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def execute(args, cwd):
    p = subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=90)
    if p.returncode:
        raise RuntimeError(f'{args[0]} failed: {p.stderr[-6000:]}')
    return {'argv':args,'stdout':p.stdout,'stderr':p.stderr}
def prepare(source, output):
    if platform.system() != 'Linux': raise ValueError('Linux target build required')
    if source.is_symlink() or not source.is_file(): raise ValueError('regular source file required')
    if sha(source) != patch.SOURCE_SHA256: raise ValueError('public source hash mismatch')
    if output.exists() or output.is_symlink(): raise ValueError('new output directory required')
    candidate = patch.patch(source.read_text())
    if hashlib.sha256(candidate.encode()).hexdigest() != CANDIDATE_SOURCE_SHA256:
        raise ValueError('transformation differs from reviewed candidate source')
    return candidate

def build(source, output):
    candidate = prepare(source, output)
    output.mkdir(parents=True)
    own = Path(__file__).resolve().parent
    for name in FILES: shutil.copy2(own/name,output/name)
    (output/'pristine.c').write_bytes(source.read_bytes())
    (output/'bridge.c').write_text(candidate)
    records=[]
    def run(*args):
        result=execute(list(args),output);records.append(result);return result
    run('gcc','-O2','-o','pristine','pristine.c','-pthread','-lm')
    run('gcc','-O2','-o','slmbridge','bridge.c','-pthread','-lm')
    run('gcc','-O2','-Wall','-Wextra','-Werror','-o','transport-test','test_transport.c')
    run('./transport-test')
    run('gcc','-O2','-o','integration-test','test_integration.c','-pthread','-lm')
    run('./integration-test')
    run('python3','test_build.py')
    run('gcc','-O2','-o','helper-only','helper-only.c','-pthread','-lm')
    cycles=[]
    for payload in (320,8192):
        for buffers in ('small','default'):
            for rate in (8000,9600):
                result=run('python3','continuous-cycle.py',str(payload),buffers,str(rate))
                evidence=json.loads(result['stdout'])
                if payload == 320:
                    if not evidence['complete_exactly']:
                        raise RuntimeError('ordinary 20ms paced cycle did not finish exactly')
                    if not re.search(r'error=0 .*to_first_pending=0 to_second_pending=0 partial_input=0 ',evidence['stderr']):
                        raise RuntimeError('ordinary paced cycle has unaccounted output')
                elif not evidence['complete_exactly']:
                    # Repeated maximum frames preserve the old one-TX-per-TLV
                    # contract but are not sample-balanced. Containment is an
                    # explicitly limited outcome, never a delivery success.
                    if not (evidence['returncode']==1 and evidence['seconds']<14 and
                            f'error={errno.ETIMEDOUT} ' in evidence['stderr']):
                        raise RuntimeError('maximum-frame stress neither completed nor failed visibly within bound')
                cycles.append(evidence)
    run('gcc','-O2','-o','timer-after-stall','timer-after-stall.c','-pthread','-lm')
    run('./timer-after-stall')
    manifest={
        'base_commit':BASE_COMMIT,'source_sha256':sha(output/'pristine.c'),
        'candidate_source_sha256':sha(output/'bridge.c'),
        'candidate_binary_sha256':sha(output/'slmbridge'),
        'pristine_binary_sha256':sha(output/'pristine'),
        'compiler':execute(['gcc','--version'],output)['stdout'].splitlines()[0],
        'architecture':platform.machine(),
        'artifacts':{p.name:sha(p) for p in sorted(output.iterdir()) if p.is_file()},
        'cycles':cycles,'commands':records,
        'physical_validation':False,'source_to_deployed_binary_claim':False,
        'runtime_scope':'Generated bytes, local AF_UNIX socketpairs, and test-owned helper functions only; no bridge main, network listener, TTY, modem, DSP or service.',
    }
    (output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--source',type=Path,default=Path(__file__).resolve().parents[2]/'slmbridge.c')
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    m=build(args.source.absolute(),args.output.absolute())
    print(json.dumps({k:m[k] for k in ('base_commit','candidate_source_sha256','candidate_binary_sha256','physical_validation')},indent=2))
